function notes(events, defaultVelocity = 0.5) {
  return events.map(([beat, midi, duration, velocity = defaultVelocity]) => ({ beat, midi, duration, velocity }));
}

function bar(section, chord, melody, figure, bassShape = 'held', warmth = 1, pad = true) {
  const harmony = HARMONY[chord];
  const bass = bassShape === 'rest' ? [] : bassShape === 'answer'
    ? [[0, harmony.root, 2.25, 0.31], [2.75, harmony.fifth, 1.05, 0.24]]
    : bassShape === 'late' ? [[0.5, harmony.root, 3.1, 0.27]]
      : bassShape === 'step' ? [[0, harmony.root, 1.75, 0.3], [2.25, harmony.fifth, 1.45, 0.25]]
        : [[0, harmony.root, 3.5, 0.29]];
  return {
    section,
    chord,
    melody: notes(melody),
    bass: notes(bass).map(note => ({ ...note, velocity: Number((note.velocity * warmth).toFixed(3)) })),
    arpeggio: FIGURES[figure].map(([beat, key, duration, velocity]) => ({
      beat, midi: harmony.keys[key], duration, velocity: Number((velocity * warmth).toFixed(3)),
    })),
    pad: pad ? [...harmony.pad] : [],
  };
}

